"""Measure the Nokia photo once: LCD rectangle and one clip-path polygon per key, in percent of the image.
Writes web/src/hits.ts.  Run: uv run --with pillow scripts/measure_phone.py  (then rebuild web/)"""
import math, os, json
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
im = Image.open(os.path.join(ROOT, "web", "public", "nokia3310.png")).convert("RGBA")
W, H = im.size
S = 2  # analysis scale
sm = im.resize((W // S, H // S)); sp = sm.load(); w2, h2 = sm.size


def components(pred, minpx, maxpx, ymin=0):
    mask = [[1 if (y * S >= ymin and pred(*sp[x, y])) else 0 for x in range(w2)] for y in range(h2)]
    seen = [[0] * w2 for _ in range(h2)]; out = []
    for y in range(h2):
        for x in range(w2):
            if mask[y][x] and not seen[y][x]:
                st = [(x, y)]; seen[y][x] = 1; pts = []
                while st:
                    cx, cy = st.pop(); pts.append((cx, cy))
                    for nx, ny in ((cx + 1, cy), (cx - 1, cy), (cx, cy + 1), (cx, cy - 1)):
                        if 0 <= nx < w2 and 0 <= ny < h2 and mask[ny][nx] and not seen[ny][nx]:
                            seen[ny][nx] = 1; st.append((nx, ny))
                if minpx <= len(pts) <= maxpx:
                    out.append(pts)
    return out


def hull_polygon(pts, n=24, grow=1.03):
    """Outline as n points: farthest pixel per angular sector around the centroid, slightly grown."""
    cx = sum(p[0] for p in pts) / len(pts); cy = sum(p[1] for p in pts) / len(pts)
    best = [None] * n
    for x, y in pts:
        a = int((math.atan2(y - cy, x - cx) + math.pi) / (2 * math.pi) * n) % n
        r = math.hypot(x - cx, y - cy)
        if best[a] is None or r > best[a][0]:
            best[a] = (r, x, y)
    poly = [(cx + (b[1] - cx) * grow, cy + (b[2] - cy) * grow) for b in best if b]
    return [(x * S, y * S) for x, y in poly]


light = lambda r, g, b, a: a > 200 and min(r, g, b) > 135 and max(r, g, b) - min(r, g, b) < 45
cyan = lambda r, g, b, a: a > 200 and b > r + 40 and g > r + 20
lcdc = lambda r, g, b, a: a > 200 and abs(r - 109) < 35 and abs(g - 144) < 35 and abs(b - 92) < 35

lcd = max(components(lcdc, 500, 10**9), key=len)
lx = [p[0] for p in lcd]; ly = [p[1] for p in lcd]
L = (min(lx) * S, min(ly) * S, (max(lx) + 1) * S, (max(ly) + 1) * S)

keys = components(light, 150, 2500, ymin=L[3] + 20)
import sys; print("blobs:", sorted(len(p) for p in keys), file=sys.stderr)
keys += components(cyan, 20, 3000, ymin=L[3] + 20)  # the navi key's blue bar
# merge navi: light arc + blue bar (overlapping y range near the top)
cx_of = lambda p: sum(q[0] for q in p) / len(p) * S
cy_of = lambda p: sum(q[1] for q in p) / len(p) * S
top_of = lambda p: min(q[1] for q in p) * S
# navi key: the light arc + blue bar right under the LCD, horizontally centred
navi_parts = [p for p in keys if top_of(p) < L[3] + 0.06 * H and abs(cx_of(p) - W / 2) < 0.2 * W]
keys = [p for p in keys if p not in navi_parts]
named = {"navi": [q for p in navi_parts for q in p]}
# C key and rocker: the two blobs in the band below the navi key, left and right
band = [p for p in keys if cy_of(p) < L[3] + 0.15 * H]
named["c"], named["rocker"] = sorted(band, key=cx_of)[0], sorted(band, key=cx_of)[-1]
digits = sorted([p for p in keys if p not in band], key=cy_of)
assert len(digits) == 12, f"expected 12 digit keys, found {len(digits)}"
rows = [sorted(digits[i:i + 3], key=lambda p: sum(q[0] for q in p) / len(p)) for i in range(0, 12, 3)]
for row, labels in zip(rows, ["123", "456", "789", "*0#"]):
    for p, lab in zip(row, labels):
        named[lab] = p


def box(pts):
    """-> React style dict: bounding box in % of the photo + clip-path polygon in % of the box."""
    poly = hull_polygon(pts)
    xs = [p[0] for p in poly]; ys = [p[1] for p in poly]
    x0, y0, x1, y1 = min(xs), min(ys), max(xs), max(ys)
    clip = ", ".join(f"{(x - x0) / (x1 - x0) * 100:.1f}% {(y - y0) / (y1 - y0) * 100:.1f}%" for x, y in poly)
    return {"left": f"{x0/W*100:.2f}%", "top": f"{y0/H*100:.2f}%", "width": f"{(x1-x0)/W*100:.2f}%", "height": f"{(y1-y0)/H*100:.2f}%",
            "clipPath": f"polygon({clip})"}


lcd_style = {"left": f"{L[0]/W*100:.2f}%", "top": f"{L[1]/H*100:.2f}%", "width": f"{(L[2]-L[0])/W*100:.2f}%", "height": f"{(L[3]-L[1])/H*100:.2f}%"}
out = "// Hit areas over the real keys, in percent of the photo. Generated by scripts/measure_phone.py, do not edit by hand.\n"
out += 'import type { CSSProperties } from "react";\n\n'
out += f"export const LCD: CSSProperties = {json.dumps(lcd_style)};\n"
out += f"export const NAVI: CSSProperties = {json.dumps(box(named['navi']))};\n"
out += f"export const CLEAR: CSSProperties = {json.dumps(box(named['c']))};\n"
out += f"export const ROCKER: CSSProperties = {json.dumps(box(named['rocker']))};  // split in two halves by CSS: prev | next\n"
out += "export const DIGITS: [string, CSSProperties][] = [\n" + "".join(f"  [{json.dumps(lab)}, {json.dumps(box(named[lab]))}],\n" for lab in "123456789*0#") + "];\n"
dest = os.path.join(ROOT, "web", "src", "hits.ts")
open(dest, "w").write(out)
print("wrote", os.path.relpath(dest, ROOT))

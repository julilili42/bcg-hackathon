#!/usr/bin/env python3
"""Print the SQLite DDL for the SQLAlchemy metadata. `make schema` writes it to schema.sql."""

from __future__ import annotations

from sqlalchemy.dialects import sqlite
from sqlalchemy.schema import CreateIndex, CreateTable

from reach.storage.db import metadata


def main() -> None:
    print("-- Generated by scripts/dump_schema.py from reach.storage.db metadata (SQLite dialect).")
    print("-- Azure SQL uses the same metadata through SQLAlchemy; do not edit by hand.")
    for table in metadata.sorted_tables:
        print(str(CreateTable(table).compile(dialect=sqlite.dialect())).strip() + ";")
        for index in table.indexes:
            print(str(CreateIndex(index).compile(dialect=sqlite.dialect())).strip() + ";")
        print()


if __name__ == "__main__":
    main()
